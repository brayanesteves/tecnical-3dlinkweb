package org.springframework.samples.petclinic.vet.domain;

import java.io.Serializable;
import java.util.Objects;

public class SpecialtyModel implements Serializable {

	private Integer id;

	private String name;

	public SpecialtyModel() {
	}

	public SpecialtyModel(Integer id, String name) {
		this.id = id;
		this.name = name;
	}

	public Integer getId() {
		return this.id;
	}

	public void setId(Integer id) {
		this.id = id;
	}

	public String getName() {
		return this.name;
	}

	public void setName(String name) {
		this.name = name;
	}

	@Override
	public boolean equals(Object o) {
		if (this == o) {
			return true;
		}
		if (o == null || getClass() != o.getClass()) {
			return false;
		}
		SpecialtyModel that = (SpecialtyModel) o;
		return Objects.equals(this.id, that.id) && Objects.equals(this.name, that.name);
	}

	@Override
	public int hashCode() {
		return Objects.hash(this.id, this.name);
	}

}
